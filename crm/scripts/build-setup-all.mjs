#!/usr/bin/env node
/*
 * Bundles every migration, in order, plus the catalogue seed into
 * supabase/setup-all.sql: the one file to paste into the Supabase SQL Editor
 * of a new project.
 *
 *   node scripts/build-setup-all.mjs      # from crm/
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const SUPABASE = path.join(here, '..', 'supabase');
const OUT = path.join(SUPABASE, 'setup-all.sql');

const migrations = readdirSync(path.join(SUPABASE, 'migrations'))
  .filter((f) => /^\d{3}_.*\.sql$/.test(f))
  .sort();
const seeds = readdirSync(path.join(SUPABASE, 'seed')).filter((f) => f.endsWith('.sql')).sort();

const banner = (label) => `

-- ═══════════════════════════════════════════════════════════════
-- ${label}
-- ═══════════════════════════════════════════════════════════════

`;

let sql = `-- OccasionsBox CRM — complete schema and catalogue, in one file.
--
-- Paste this whole file into the Supabase SQL Editor of a NEW, EMPTY project
-- and run it once. It is the ${migrations.length} migrations in supabase/migrations/ followed by
-- the catalogue seed in supabase/seed/, concatenated in their required order.
--
-- Do NOT run this against a project that already has the CRM schema: section 1
-- uses plain CREATE TABLE and will fail on the first existing table. To bring an
-- older CRM database up to date instead, run 006, 007 and the seed, each of
-- which is written to be idempotent.
--
-- GENERATED by crm/scripts/build-setup-all.mjs. Edit the parts, not this file.
-- After running, follow "Supabase Auth URL configuration" in crm/README.md.
`;

for (const f of migrations) sql += banner(`migrations/${f}`) + readFileSync(path.join(SUPABASE, 'migrations', f), 'utf8');
for (const f of seeds) sql += banner(`seed/${f}`) + readFileSync(path.join(SUPABASE, 'seed', f), 'utf8');

writeFileSync(OUT, sql);
console.log(`supabase/setup-all.sql: ${migrations.length} migrations + ${seeds.length} seed file(s), ${sql.split('\n').length} lines`);
